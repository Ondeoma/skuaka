package skuaka.core

/**
 * skuaka のエラーコード（すべてのエラーをここにまとめる）.
 * 1xxx: 認証・共通（ログイン・API トークン・プロフィール・リクエスト）, 2xxx: カレンダー（共有・公開・配信）, 3xxx: 予定（招待・返事）,
